from . import _discretize as dct
from ._utilities import export

# Public function aliases
adaptive_curve = dct.adaptive_curve
uniform_curve = dct.uniform_curve
recompute_error = dct.recompute_error
curve_curvature = dct.curve_curvature


@export
class AdaptiveDiscretization:
    """Stores the result of an adaptive curve discretization.

    The class provides the discretized curve parameters and points together with the per-segment sampling
    diagnostics that make the discretization error reproducible. It is produced by :func:`.adaptive_curve` and is
    intentionally read-only: re-running :func:`.adaptive_curve` (or :func:`.recompute_error`) with the same
    arguments reproduces the same data.

    Attributes:
        tolerance: maximum sagitta requested through the ``tolerance`` keyword argument
        max_length: maximum chord length applied through the arc length criterion
        max_depth: maximum number of midpoint subdivisions per segment
        max_error: maximum sagitta observed among the accepted segments
        arc_length: polyline length of the discretization (sum of the segment chord lengths)
        max_subdivision_depth: deepest subdivision level actually reached
        saturated: ``True`` if at least one segment hit ``max_depth`` before meeting the criteria
    """

    def __init__(self, **kwargs):
        self._curve = kwargs.get("curve")
        self._parameters = kwargs.get("parameters", [])
        self._points = kwargs.get("points", [])
        self._segments = kwargs.get("segments", [])
        self.tolerance = kwargs.get("tolerance")
        self.max_length = kwargs.get("max_length")
        self.max_depth = kwargs.get("max_depth")
        self.max_error = kwargs.get("max_error", 0.0)
        self.arc_length = kwargs.get("arc_length", 0.0)
        self.max_subdivision_depth = kwargs.get("max_subdivision_depth", 0)
        self.saturated = kwargs.get("saturated", False)

    def __len__(self):
        return len(self._points)

    def __iter__(self):
        return iter(self._points)

    @property
    def curve(self):
        """The curve that has been discretized.

        :getter: Gets the input curve
        :type: abstract.Curve
        """
        return self._curve

    @property
    def parameters(self):
        """Strictly increasing parameters of the discretized points.

        The first and the last parameters are the discretization interval endpoints and every interior parameter
        is a midpoint generated by the recursive subdivision.

        :getter: Gets the curve parameters
        :type: list
        """
        return self._parameters

    @property
    def points(self):
        """Evaluated curve points corresponding to :py:attr:`parameters`.

        :getter: Gets the evaluated points
        :type: list
        """
        return self._points

    @property
    def segments(self):
        """Per-segment diagnostics of the adaptive discretization.

        Every segment is a dictionary containing its parameter interval, the evaluated endpoint and midpoint
        points, the chord length, the midpoint sagitta, the curvature-weighted residual and the subdivision depth
        at which it was accepted.

        :getter: Gets the segment reports
        :type: list
        """
        return self._segments

    def recompute(self, **kwargs):
        """Recomputes the discretization error from the curve independently.

        This is a convenience wrapper around :func:`.recompute_error` using the stored parameters. The tolerance
        can be overridden through the ``tolerance`` keyword argument.

        :return: error report recomputed directly from the curve
        :rtype: dict
        """
        kwargs.setdefault("tolerance", self.tolerance)
        return recompute_error(self._curve, self._parameters, **kwargs)
